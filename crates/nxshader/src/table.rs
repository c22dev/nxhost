const ENCODING_BITS: u32 = 14;

pub fn decode(opcode: u64) -> (InstName, Op, InstProps) {
    static TABLE: OnceLock<Vec<(InstName, Op, InstProps, u32)>> = OnceLock::new();
    let t = TABLE.get_or_init(|| {
        let mut t = vec![(InstName::Invalid, Op::Invalid, InstProps::NONE, u32::MAX); 1 << ENCODING_BITS];
        for &(pat, name, op, props) in ENCODINGS {
            let head = &pat.as_bytes()[..ENCODING_BITS as usize];
            let xs: Vec<u32> = head.iter().enumerate().filter(|(_, c)| **c == b'x').map(|(i, _)| ENCODING_BITS - 1 - i as u32).collect();
            let base: u32 = head.iter().enumerate().filter(|(_, c)| **c == b'1').map(|(i, _)| 1 << (ENCODING_BITS - 1 - i as u32)).sum();
            for k in 0..(1u32 << xs.len()) {
                let v = xs.iter().enumerate().fold(base, |v, (b, &pos)| v | ((k >> b) & 1) << pos);
                let e = &mut t[v as usize];
                if e.3 == u32::MAX || e.3 > xs.len() as u32 {
                    *e = (name, op, props, xs.len() as u32);
                }
            }
        }
        t
    });
    let e = t[(opcode >> (64 - ENCODING_BITS)) as usize];
    (e.0, e.1, e.2)
}

pub fn lookup(opcode: u64) -> (InstName, InstProps) {
    let (n, _, p) = decode(opcode);
    (n, p)
}
