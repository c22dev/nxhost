#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub struct InstProps(pub u16);
impl InstProps {
    pub const NONE: InstProps = InstProps(0);
    pub const RD: InstProps = InstProps(1 << 0);
    pub const RD2: InstProps = InstProps(1 << 1);
    pub const RA: InstProps = InstProps(1 << 2);
    pub const RB: InstProps = InstProps(1 << 3);
    pub const RB2: InstProps = InstProps(1 << 4);
    pub const IB: InstProps = InstProps(1 << 5);
    pub const RC: InstProps = InstProps(1 << 6);
    pub const PD: InstProps = InstProps(1 << 7);
    pub const LPD: InstProps = InstProps(2 << 7);
    pub const SPD: InstProps = InstProps(3 << 7);
    pub const TPD: InstProps = InstProps(4 << 7);
    pub const VPD: InstProps = InstProps(5 << 7);
    pub const PDMASK: InstProps = InstProps(7 << 7);
    pub const PDN: InstProps = InstProps(1 << 10);
    pub const PS: InstProps = InstProps(1 << 11);
    pub const TEX: InstProps = InstProps(1 << 12);
    pub const TEXB: InstProps = InstProps(1 << 13);
    pub const BRA: InstProps = InstProps(1 << 14);
    pub const NOPRED: InstProps = InstProps(1 << 15);
    pub fn has(self, f: InstProps) -> bool { self.0 & f.0 == f.0 && f.0 != 0 }
    pub fn pd_kind(self) -> u16 { self.0 & Self::PDMASK.0 }
}
impl std::ops::BitOr for InstProps { type Output = Self; fn bitor(self, o: Self) -> Self { InstProps(self.0 | o.0) } }

